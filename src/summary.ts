/** Markdown summary for the PR comment and $GITHUB_STEP_SUMMARY. */
import type { Report, TestCase } from './types.js';
import { formatDuration, passRate, truncate } from './util.js';

export const COMMENT_MARKER = '<!-- spectra-report -->';

function esc(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\r?\n/g, ' ');
}

function testName(t: TestCase): string {
  return esc(truncate(t.titlePath.join(' › '), 90)) + (t.project ? ` <sub>${esc(t.project)}</sub>` : '');
}

function link(report: Report, hash: string): string {
  return report.reportUrl ? `${report.reportUrl.replace(/\/?$/, '/')}#${hash}` : '';
}

export function renderSummary(report: Report, opts: { maxRows?: number } = {}): string {
  const max = opts.maxRows ?? 10;
  const s = report.stats;
  const ok = s.failed === 0;
  const rate = (passRate(s) * 100).toFixed(1);
  const lines: string[] = [COMMENT_MARKER];
  lines.push(`## ${ok ? '✅' : '❌'} Spectra Report: ${s.passed} passed, ${s.failed} failed, ${s.flaky} flaky, ${s.skipped} skipped`);
  const meta = [`**Pass rate** ${rate}%`, `**Duration** ${formatDuration(report.run.durationMs)}`];
  if (report.run.ci?.commit) meta.push(`**Commit** \`${report.run.ci.commit.slice(0, 7)}\``);
  if (report.reportUrl) meta.push(`[**Open full report →**](${report.reportUrl})`);
  lines.push(meta.join(' · '), '');

  const byId = new Map(report.tests.map((t) => [t.id, t]));
  const failed = report.tests.filter((t) => t.status === 'failed');
  const fresh = failed.filter((t) => t.isNewFailure);
  const known = failed.filter((t) => !t.isNewFailure);

  if (fresh.length) {
    lines.push(`### 🆕 New failures (${fresh.length})`, '', '| Test | Project | Likely cause |', '| --- | --- | --- |');
    for (const t of fresh.slice(0, max)) {
      const c = report.clusters.find((x) => x.id === t.clusterId);
      const cause = c?.ai?.summary ?? c?.title ?? '';
      const title = esc(truncate(t.titlePath.join(' › '), 90));
      const name = report.reportUrl ? `[${title}](${link(report, `/test/${t.id}`)})` : title;
      lines.push(`| ${name} | ${esc(t.project ?? '')} | ${esc(truncate(cause, 120))} |`);
    }
    if (fresh.length > max) lines.push('', `…and ${fresh.length - max} more.`);
    lines.push('');
  }
  if (known.length) {
    lines.push(`### Still failing (${known.length})`, '', known.slice(0, max).map((t) => `- ${testName(t)}`).join('\n'));
    if (known.length > max) lines.push(`- …and ${known.length - max} more`);
    lines.push('');
  }

  if (report.clusters.length) {
    lines.push(`### Failure groups (${report.clusters.length})`, '');
    for (const c of report.clusters.slice(0, 5)) {
      const badge = c.ai ? ` · ${c.ai.category} · ${Math.round(c.ai.confidence * 100)}% confidence` : '';
      lines.push(`<details><summary><b>${esc(truncate(c.title, 110))}</b>: ${c.testIds.length} test${c.testIds.length === 1 ? '' : 's'}${badge}</summary>`, '');
      if (c.ai) {
        lines.push(`**AI hint:** ${esc(c.ai.summary)}`, '');
        lines.push(`**Likely cause:** ${esc(c.ai.likelyCause)}`, '');
        lines.push(`**Suggested fix:** ${esc(c.ai.suggestedFix)}`, '');
      }
      const examples = c.testIds.slice(0, 5).map((id) => byId.get(id)).filter((t): t is TestCase => !!t);
      lines.push(examples.map((t) => `- ${testName(t)}`).join('\n'));
      lines.push('', '```', truncate(c.sampleError, 600), '```', '', '</details>', '');
    }
  }

  const flaky = report.tests.filter((t) => t.status === 'flaky');
  if (flaky.length) {
    lines.push(`### 🔁 Flaky (${flaky.length}): passed on retry`, '');
    lines.push(flaky.slice(0, max).map((t) => `- ${testName(t)} (flake rate ${Math.round((t.flakeRate ?? 0) * 100)}%)`).join('\n'), '');
  }

  if (!failed.length && !flaky.length) lines.push('All tests passed. 🎉', '');
  lines.push(`<sub>Generated by [Spectra Report](https://github.com/surkuar/spectra-report). AI hints are suggestions, not verified diagnoses.</sub>`);
  return truncate(lines.join('\n'), 60000);
}
